const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../apps/mobile/dist');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.match(html, /viewport-fit=cover/, 'Export must retain the iPhone safe-area viewport');
assert.match(html, /name="apple-mobile-web-app-capable" content="yes"/);
assert.match(html, /rel="manifest" href="\/manifest.webmanifest"/);
assert.match(html, /rel="apple-touch-icon" href="\/app-icon.png"/);
assert.match(html, /id="root"/);
assert.doesNotMatch(html, /%WEB_TITLE%|%LANG_ISO_CODE%/, 'Expo must process the template');
const script = html.match(/<script[^>]+src="(\/_expo\/static\/js\/web\/[^"/]+\.js)"/);
assert.ok(script, 'Export must include its generated app bundle');
assert.ok(fs.existsSync(path.join(root, script[1])), 'App bundle must exist');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.webmanifest'), 'utf8'));
assert.equal(manifest.display, 'standalone');
assert.equal(manifest.start_url, '/');
const icon = fs.readFileSync(path.join(root, 'app-icon.png'));
assert.equal(icon.readUInt32BE(16), 1024);
assert.equal(icon.readUInt32BE(20), 1024);
console.log('Web export: app bundle, safe-area viewport, Home Screen metadata and icon verified.');
